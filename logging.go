package main

import (
	"log/slog"
	"os"
)

// setupSlog configures the default slog logger for internal diagnostics.
// Output goes to stderr (the journal under systemd). Events a human has to
// act on are not reported here but through the notifier.
func setupSlog(debug bool) {
	level := slog.LevelInfo
	if debug {
		level = slog.LevelDebug
	}
	slog.SetDefault(slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: level})))
}
